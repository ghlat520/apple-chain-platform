-- ---------------------------------------------------------------------
-- td_wx_payment — 微信支付记录
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS td_wx_payment (
    id              BIGINT        NOT NULL PRIMARY KEY COMMENT '雪花 ID',
    out_trade_no    VARCHAR(64)   NOT NULL COMMENT '商户订单号（唯一）',
    order_id        BIGINT        NULL     COMMENT '关联业务订单 ID',
    amount_cents    BIGINT        NOT NULL COMMENT '金额（分）',
    status          TINYINT       NOT NULL DEFAULT 1 COMMENT '1=PENDING 2=SUCCESS 3=FAILED 4=REFUNDED',
    pay_method      VARCHAR(16)   NOT NULL DEFAULT 'WECHAT' COMMENT '支付方式',
    prepay_id       VARCHAR(64)   NULL     COMMENT '微信预支付会话 ID（Mock）',
    transaction_id  VARCHAR(64)   NULL     COMMENT '微信支付订单号（Mock）',
    pay_time        DATETIME      NULL     COMMENT '支付完成时间',
    description     VARCHAR(255)  NULL     COMMENT '商品描述',
    create_time     DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time     DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    create_by       VARCHAR(64)   NULL,
    deleted         TINYINT       NOT NULL DEFAULT 0,
    UNIQUE KEY uk_wx_payment_out_trade_no (out_trade_no),
    KEY idx_wx_payment_order_id (order_id),
    KEY idx_wx_payment_status (status),
    KEY idx_wx_payment_pay_time (pay_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='微信支付 Mock 记录';

-- ---------------------------------------------------------------------
-- td_wx_refund — 微信退款记录
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS td_wx_refund (
    id                  BIGINT        NOT NULL PRIMARY KEY COMMENT '雪花 ID',
    out_refund_no       VARCHAR(64)   NOT NULL COMMENT '商户退款单号（唯一）',
    payment_id          BIGINT        NOT NULL COMMENT '关联支付记录 ID',
    refund_amount_cents BIGINT        NOT NULL COMMENT '退款金额（分）',
    reason              VARCHAR(255)  NULL     COMMENT '退款原因',
    status              TINYINT       NOT NULL DEFAULT 2 COMMENT '1=PENDING 2=SUCCESS 3=FAILED',
    refund_id           VARCHAR(64)   NULL     COMMENT '微信退款单号（Mock）',
    refund_time         DATETIME      NULL     COMMENT '退款完成时间',
    create_time         DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time         DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    create_by           VARCHAR(64)   NULL,
    deleted             TINYINT       NOT NULL DEFAULT 0,
    UNIQUE KEY uk_wx_refund_out_refund_no (out_refund_no),
    KEY idx_wx_refund_payment_id (payment_id),
    KEY idx_wx_refund_status (status),
    KEY idx_wx_refund_refund_time (refund_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='微信退款 Mock 记录';

